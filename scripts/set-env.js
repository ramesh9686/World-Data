const fs = require('fs');
const path = require('path');

// Load .env if present
const envPath = path.resolve(__dirname, '../.env');
const envVars = {};

if (fs.existsSync(envPath)) {
  const content = fs.readFileSync(envPath, 'utf-8');
  content.split('\n').forEach(line => {
    const trimmed = line.trim();
    if (trimmed && !trimmed.startsWith('#')) {
      const eqIdx = trimmed.indexOf('=');
      if (eqIdx !== -1) {
        const key = trimmed.slice(0, eqIdx).trim();
        const val = trimmed.slice(eqIdx + 1).trim();
        envVars[key] = val;
      }
    }
  });
}

const aisApiKey = process.env.AISSTREAM_API_KEY || envVars.AISSTREAM_API_KEY || '';
const gfwApiKey = process.env.GFW_API_KEY || envVars.GFW_API_KEY || '';

const envDir = path.resolve(__dirname, '../src/environments');
if (!fs.existsSync(envDir)) {
  fs.mkdirSync(envDir, { recursive: true });
}

// Production environment
const prodEnvContent = `// Auto-generated by scripts/set-env.js - DO NOT COMMIT SECRETS
export const environment = {
  production: true,
  aisStreamApiKey: '${aisApiKey}',
  gfwApiKey: '${gfwApiKey}'
};
`;

// Development environment
const devEnvContent = `// Auto-generated by scripts/set-env.js - DO NOT COMMIT SECRETS
export const environment = {
  production: false,
  aisStreamApiKey: '${aisApiKey}',
  gfwApiKey: '${gfwApiKey}'
};
`;

fs.writeFileSync(path.join(envDir, 'environment.ts'), prodEnvContent, 'utf-8');
fs.writeFileSync(path.join(envDir, 'environment.development.ts'), devEnvContent, 'utf-8');

console.log('[Security] Environment configuration successfully injected from .env / process.env');
